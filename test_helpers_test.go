func initTempRepo(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()

	run := func(args ...string) {
		t.Helper()
		cmd := exec.Command("git", append([]string{"-C", dir}, args...)...)
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v failed: %v\n%s", args, err, string(out))
		}
	}

	run("init", "-b", "main")
	run("config", "user.name", "Test User")
	run("config", "user.email", "test@example.com")

	writeRepoFile(t, dir, "README.md", "# Hello\n")
	run("add", "README.md")
	run("commit", "-m", "initial commit")

	origDir, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		_ = os.Chdir(origDir)
	})
	return dir
}

func writeRepoFile(t *testing.T, root, relPath, content string) {
	t.Helper()
	full := filepath.Join(root, filepath.FromSlash(relPath))
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func setMockStdin(t *testing.T, input string) {
	t.Helper()
	oldStdin := stdin
	oldTerm := stdinIsTerminal
	stdin = bufio.NewReader(strings.NewReader(input))
	stdinIsTerminal = true
	t.Cleanup(func() {
		stdin = oldStdin
		stdinIsTerminal = oldTerm
	})
}

func captureOutput(t *testing.T, fn func()) string {
	t.Helper()
	prevColor := useColor
	useColor = false
	defer func() { useColor = prevColor }()

	r, w, err := os.Pipe()
	if err != nil {
		t.Fatal(err)
	}
	oldStdout := os.Stdout
	os.Stdout = w

	done := make(chan string)
	go func() {
		var buf bytes.Buffer
		_, _ = io.Copy(&buf, r)
		done <- buf.String()
	}()

	fn()
	_ = w.Close()
	os.Stdout = oldStdout
	out := <-done
	_ = r.Close()
	return out
}